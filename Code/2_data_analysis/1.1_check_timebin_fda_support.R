feasible_bins <- timebin_overall %>%
  filter(case_bin_support_ok, control_bin_support_ok)

suggested_window <- if (nrow(feasible_bins) == 0) {
  "No 2-year relative-time bins met both case and control support thresholds."
} else if (nrow(feasible_bins) == length(rel_labels)) {
  "All prespecified bins met support thresholds, including <= -16 years and > +16 years"
} else {
  paste(
    "Supported bins:",
    paste(as.character(feasible_bins$rel_time_bin), collapse = ", ")
  )
}

