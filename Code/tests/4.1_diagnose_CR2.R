matched_long <- readRDS(matched_path)
needed_cols <- c(
  "Cohort", "Group", "Age_Centered", "index_age_z", "base_race",
  "base_marital", "base_living", "id", "match_set", "role", "cycle",
  "fi_score_nocancer", "post_own_cancer"
)
missing_cols <- setdiff(needed_cols, names(matched_long))
if (length(missing_cols)) {
  stop("Matched dataset is missing required columns: ",
       paste(missing_cols, collapse = ", "), call. = FALSE)
}

if (!("matching_id" %in% names(matched_long))) {
  matched_long$matching_id <- paste(
    matched_long$Cohort, matched_long$match_set, sep = "__"
  )
}
if (!("trajectory_id" %in% names(matched_long))) {
  matched_long$trajectory_id <- paste(
    matched_long$Cohort, matched_long$match_set, matched_long$id,
    matched_long$role, sep = "__"
  )
}

matched_long <- matched_long %>%
  mutate(
    Cohort = droplevels(factor(Cohort)),
    Group = factor(Group, levels = c("Control", "Cancer Case")),
    id = factor(id),
    match_set = factor(match_set),
    matching_id = factor(matching_id),
    trajectory_id = factor(trajectory_id),
    base_race = factor(base_race),
    base_marital = factor(base_marital),
    base_living = factor(base_living)
  ) %>%
  filter(!post_own_cancer, !is.na(fi_score_nocancer), !is.na(Age_Centered)) %>%
  add_relative_time_bin()

if (anyDuplicated(paste(matched_long$trajectory_id, matched_long$cycle, sep = "__"))) {
  stop("Duplicated trajectory_id x cycle rows remain after primary filtering.",
       call. = FALSE)
}

for (cohort in levels(matched_long$Cohort)) {
  d_base <- matched_long %>% filter(Cohort == cohort) %>% droplevels()
  prepared <- capture_call(prepare_m1_data(d_base))
  if (!is.na(prepared$error)) {
    add_row(cohort, "data_preparation_failed", stage = "data_preparation",
            status = "error", message = prepared$error)
    next
  }

  d_model <- prepared$value$data
  fit_warnings <- character()
  fitted <- capture_call(withCallingHandlers(
    lme4::lmer(
      prepared$value$formula,
      data = d_model,
      REML = TRUE,
      control = lme4::lmerControl(
        optimizer = "bobyqa",
        calc.derivs = TRUE,
        optCtrl = list(maxfun = 2e5)
      )
    ),
    warning = function(w) {
      fit_warnings <<- c(fit_warnings, conditionMessage(w))
      invokeRestart("muffleWarning")
    }
  ))
  if (!is.na(fitted$error)) {
    add_row(cohort, "fit_failed", stage = "model_fit", status = "error",
            message = fitted$error, n_model_rows = nrow(d_model))
    next
  }

  fit_check <- .assess_lmer_fit(fitted$value)
  fit_status <- if (isTRUE(fit_check$converged) && !length(fit_warnings)) {
    "accepted"
  } else {
    "not_strictly_accepted"
  }
  fit_message <- paste(c(fit_check$convergence_messages, fit_warnings),
                       collapse = " | ")
  add_row(
    cohort, fit_status, stage = "model_fit", status = "success",
    message = if (nzchar(fit_message)) fit_message else NA_character_,
    n_model_rows = nrow(d_model),
    n_model_frame_rows = nrow(model.frame(fitted$value))
  )
  diagnose_covariance(fitted$value, cohort, fit_status, d_model)
}

