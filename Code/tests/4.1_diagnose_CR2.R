add_row <- function(cohort, fit_status, cr_type = NA_character_,
                    cluster_source = NA_character_, stage, status,
                    message = NA_character_, n_model_rows = NA_integer_,
                    n_model_frame_rows = NA_integer_,
                    n_cluster_values = NA_integer_,
                    n_unique_clusters = NA_integer_,
                    n_missing_clusters = NA_integer_,
                    cluster_matches_model_frame = NA,
                    covariance_nrow = NA_integer_,
                    covariance_ncol = NA_integer_,
                    covariance_finite = NA,
                    covariance_symmetric = NA) {
  diagnostic_rows[[length(diagnostic_rows) + 1L]] <<- data.frame(
    generated_at_utc = format(Sys.time(), tz = "UTC", usetz = TRUE),
    cohort = as.character(cohort),
    model_id = "M1_primary_spline",
    fit_status = fit_status,
    cr_type = cr_type,
    cluster_source = cluster_source,
    stage = stage,
    status = status,
    message = if (is.null(message)) NA_character_ else as.character(message),
    n_model_rows = as.integer(n_model_rows),
    n_model_frame_rows = as.integer(n_model_frame_rows),
    n_cluster_values = as.integer(n_cluster_values),
    n_unique_clusters = as.integer(n_unique_clusters),
    n_missing_clusters = as.integer(n_missing_clusters),
    cluster_matches_model_frame = as.logical(cluster_matches_model_frame),
    covariance_nrow = as.integer(covariance_nrow),
    covariance_ncol = as.integer(covariance_ncol),
    covariance_finite = as.logical(covariance_finite),
    covariance_symmetric = as.logical(covariance_symmetric),
    clubSandwich_version = club_sandwich_version,
    stringsAsFactors = FALSE
  )
}

capture_call <- function(expr) {
  tryCatch(
    list(value = force(expr), error = NA_character_),
    error = function(e) list(value = NULL, error = conditionMessage(e))
  )
}

prepare_m1_data <- function(data) {
  d_spline_basis <- data %>%
    filter(if_all(all_of(.primary_covars), ~ !is.na(.x)))
  spline_bases <- list(
    adjusted_spline = .make_spline_basis(
      d_spline_basis$Age_Centered,
      spline_df = 3L,
      prefix = "S"
    )
  )
  spec <- .trajectory_model_specs$M1_primary_spline
  time_terms <- .model_time_terms(spec, spline_bases)
  d_model <- data %>%
    .add_model_time_terms(spec, spline_bases) %>%
    filter(if_all(all_of(spec$covars), ~ !is.na(.x))) %>%
    droplevels()
  scaling <- .scale_model_numeric_columns(d_model, time_terms)
  fixed_rhs <- .fixed_rhs(spline_terms = time_terms, covars = spec$covars)
  list(
    data = scaling$data,
    formula = update(fixed_rhs, fi_score_nocancer ~ . + (1 | id))
  )
}

diagnose_covariance <- function(fit, cohort, fit_status, d_model) {
  model_frame <- model.frame(fit)
  model_frame_id <- model_frame[["id"]]
  fitting_data_id <- d_model[["id"]]
  clusters_align <- length(model_frame_id) == length(fitting_data_id) &&
    identical(as.character(model_frame_id), as.character(fitting_data_id))

  add_row(
    cohort, fit_status, stage = "cluster_alignment",
    status = if (clusters_align) "success" else "mismatch",
    message = if (clusters_align) NA_character_ else
      "The fitting-data id vector differs from model.frame(fit)$id.",
    n_model_rows = nrow(d_model), n_model_frame_rows = nrow(model_frame),
    n_cluster_values = length(fitting_data_id),
    n_unique_clusters = dplyr::n_distinct(fitting_data_id),
    n_missing_clusters = sum(is.na(fitting_data_id)),
    cluster_matches_model_frame = clusters_align
  )

  cluster_sources <- list(model_frame_id = model_frame_id)
  if (!clusters_align) cluster_sources$fitting_data_id <- fitting_data_id

  for (cluster_source in names(cluster_sources)) {
    cluster <- cluster_sources[[cluster_source]]
    n_unique <- dplyr::n_distinct(cluster)
    n_missing <- sum(is.na(cluster))
    is_model_frame_cluster <- identical(cluster_source, "model_frame_id")

    for (cr_type in c("CR2", "CR0")) {
      vcov_result <- capture_call(
        clubSandwich::vcovCR(fit, cluster = cluster, type = cr_type)
      )
      if (!is.na(vcov_result$error)) {
        add_row(
          cohort, fit_status, cr_type, cluster_source, "vcovCR", "error",
          vcov_result$error, nrow(d_model), nrow(model_frame), length(cluster),
          n_unique, n_missing, is_model_frame_cluster
        )
        next
      }

      V_cs <- vcov_result$value
      V <- as.matrix(V_cs)
      covariance_finite <- all(is.finite(V))
      covariance_symmetric <- isTRUE(all.equal(V, t(V), tolerance = 1e-8))
      covariance_valid <- nrow(V) == length(lme4::fixef(fit)) &&
        ncol(V) == length(lme4::fixef(fit)) &&
        covariance_finite && covariance_symmetric
      add_row(
        cohort, fit_status, cr_type, cluster_source, "covariance_validation",
        if (covariance_valid) "success" else "invalid",
        if (covariance_valid) NA_character_ else
          "Covariance dimensions, finiteness, or symmetry check failed.",
        nrow(d_model), nrow(model_frame), length(cluster), n_unique, n_missing,
        is_model_frame_cluster, nrow(V), ncol(V), covariance_finite,
        covariance_symmetric
      )
      if (!covariance_valid) next

      coefficient_result <- capture_call(
        clubSandwich::coef_test(fit, vcov = V_cs, test = "Satterthwaite")
      )
      add_row(
        cohort, fit_status, cr_type, cluster_source, "coef_test",
        if (is.na(coefficient_result$error)) "success" else "error",
        coefficient_result$error, nrow(d_model), nrow(model_frame),
        length(cluster), n_unique, n_missing, is_model_frame_cluster
      )

      probe <- matrix(0, nrow = 1, ncol = length(lme4::fixef(fit)))
      probe[1, 1] <- 1
      wald_result <- capture_call(
        clubSandwich::Wald_test(fit, constraints = probe, vcov = V_cs,
                                test = "HTZ")
      )
      add_row(
        cohort, fit_status, cr_type, cluster_source, "Wald_test",
        if (is.na(wald_result$error)) "success" else "error",
        wald_result$error, nrow(d_model), nrow(model_frame), length(cluster),
        n_unique, n_missing, is_model_frame_cluster
      )
    }
  }
}

